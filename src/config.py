"""
Конфигурация проекта распознавания эмоций.

Адаптировано для 3 классов эмоций: Happy, Sad, Neutral.
Все параметры вынесены сюда для удобной модификации.
"""

import os

# =============================================================================
# СПИСОК ЭМОЦИЙ (3 класса)
# =============================================================================
# Изменено с 7 на 3 эмоции согласно требованиям.
# Для добавления/замены эмоций — редактируйте этот список.
EMOTIONS = ["Happy", "Sad", "Neutral"]
NUM_CLASSES = len(EMOTIONS)  # Автоматически = 3

# Индексы классов для сопоставления предсказаний с метками
EMOTION_TO_IDX = {emotion: idx for idx, emotion in enumerate(EMOTIONS)}
IDX_TO_EMOTION = {idx: emotion for idx, emotion in enumerate(EMOTIONS)}

# =============================================================================
# ПУТИ К ДАННЫМ
# =============================================================================
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASET_DIR = os.path.join(BASE_DIR, "dataset")
TRAIN_DIR = os.path.join(DATASET_DIR, "train")
TEST_DIR = os.path.join(DATASET_DIR, "test")

# Путь для сохранения обученной модели
MODEL_PATH = os.path.join(BASE_DIR, "models", "emotion_model.keras")
os.makedirs(os.path.dirname(MODEL_PATH), exist_ok=True)

# =============================================================================
# ПАРАМЕТРЫ ИЗОБРАЖЕНИЙ
# =============================================================================
# Входные изображения: 48x48, grayscale, пиксели нормализованы в [0, 1]
IMG_HEIGHT = 48
IMG_WIDTH = 48
IMG_CHANNELS = 1  # Grayscale
COLOR_MODE = "grayscale"
TARGET_SIZE = (IMG_HEIGHT, IMG_WIDTH)

# =============================================================================
# ПАРАМЕТРЫ МОДЕЛИ
# =============================================================================
# Архитектура CNN: 3 блока Conv2D + MaxPooling
CNN_FILTERS = [32, 64, 128]  # Количество фильтров в каждом блоке
CNN_KERNEL_SIZE = (3, 3)
POOL_SIZE = (2, 2)

# После 3 MaxPooling(2,2) с входом 48x48:
# 48 -> 24 -> 12 -> 6, итог: (6, 6, 128)
CNN_OUTPUT_SHAPE = (6, 6, CNN_FILTERS[-1])  # (6, 6, 128)
CNN_OUTPUT_RESHAPED = (6 * 6, CNN_FILTERS[-1])  # (36, 128) для LSTM

# BiLSTM параметры
LSTM_UNITS = 64
BIDIRECTIONAL = True

# Dense слой после Attention
DENSE_UNITS = 128
DROPOUT_RATE = 0.5

# Финальный слой: NUM_CLASSES = 3 (адаптировано с 7)
# Activation: softmax для многоклассовой классификации

# =============================================================================
# ПАРАМЕТРЫ ОБУЧЕНИЯ
# =============================================================================
BATCH_SIZE = 32
EPOCHS = 30
LEARNING_RATE = 0.001

# Оптимизатор и функция потерь
OPTIMIZER = "adam"
LOSS_FUNCTION = "categorical_crossentropy"  # Для one-hot encoded меток

# Метрики для отслеживания
METRICS = ["accuracy", "precision", "recall", "auc"]

# =============================================================================
# ПАРАМЕТРЫ ИНФЕРЕНСА (ВЕБ-КАМЕРА)
# =============================================================================
# DETECTION_SCALE: коэффициент уменьшения кадра для детекции лиц
# Уменьшение ускоряет детекцию (Haar Cascade работает быстрее на малых изображениях)
DETECTION_SCALE = 0.5  # fx=0.5, fy=0.5

# PREDICT_INTERVAL: предсказание делается не на каждом кадре, а каждые N кадров
# Это снижает нагрузку на GPU/CPU и делает вывод более плавным
PREDICT_INTERVAL = 5  # Предсказание каждые 5 кадров

# Коэффициент сглаживания для плавного вывода эмоций
SMOOTHING_FACTOR = 0.3  # Вес нового предсказания (0.3 = 30% новое, 70% старое)

# Параметры детекции лиц (Haar Cascade)
MIN_FACE_SIZE = 30  # Минимальный размер лица в пикселях

# Цвета для отрисовки (BGR формат OpenCV)
EMOTION_COLORS = {
    "Happy": (0, 255, 0),      # Зеленый
    "Sad": (0, 0, 255),        # Красный
    "Neutral": (255, 255, 0)   # Циан
}

# =============================================================================
# ИМПОРТ OPENCV (здесь для доступа к cv2.data)
# =============================================================================
try:
    import cv2
    FACE_CASCADE_PATH = cv2.data.haarcascades + "haarcascade_frontalface_default.xml"
except ImportError:
    # Если OpenCV ещё не установлен, пути к каскадам будут заданы позже
    FACE_CASCADE_PATH = None
    print("Предупреждение: OpenCV не установлен. Некоторые функции могут быть недоступны.")
